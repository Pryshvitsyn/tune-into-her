/* global __dirname */
// Authoritative V5 SVG appearance -> shared RGBA foreground + separate atmosphere.
const { Buffer } = require('node:buffer');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const { PNG } = require('pngjs');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const source = read('assets/brand/official-mark.svg');
const sourceHash = sha(source);
const backgroundSource = read('assets/brand/steel-background.svg');
const backgroundSourceHash = sha(backgroundSource);
const body = source.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const rings = body.match(/<path id="rings" d="([^"]+)"/)?.[1];
if (!rings || source.match(/viewBox="([^"]+)"/)?.[1] !== '0 0 640 400') throw new Error('Unexpected authoritative brand geometry');
if (sha(fs.readFileSync(path.join(root, 'assets/fonts/LinuxLibertineO-Regular.otf'))) !== '6332761e4fc08e30bce6f47e4a08e7d5332abe000ab6ca06c8e86bd88f456114') throw new Error('Approved typeface changed');
const reference = 'assets/brand/reference/founder-approved-premium-v5-20261114.png';
if (sha(fs.readFileSync(path.join(root, reference))) !== 'dfce7d014d6107bdad02a54886dba3bbb8e5f216065774dc7b7c34e7e3da1c58') throw new Error('Immutable Founder reference changed');
const vector = [
  '/** Generated by scripts/generate-intro-brand.cjs from assets/brand/official-mark.svg.',
  ' * Exact Linux Libertine O glyph outlines and native-default kerning; V5 metallic appearance.',
  ' * Two coherent open arcs; lettering silhouette is never replaced by generated text.',
  ' */',
  "export const BRAND_SOURCE_SHA256 = '" + sourceHash + "';",
  "export const BRAND_VIEWBOX = '0 0 640 400';",
  'export const BRAND_RATIO = 640 / 400;',
  'export const OFFICIAL_APP_MARK_PATH = ' + JSON.stringify(rings) + ';',
  'export const BRAND_BODY = ' + JSON.stringify(body) + ';',
  "export function brandSvg(ink = '#294458'): string {",
  "  if (!/^#[0-9a-fA-F]{6}$/.test(ink)) throw new Error('Invalid brand ink');",
  '  return \'<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="800" viewBox="\' + BRAND_VIEWBOX + \'" color="\' + ink + \'">\' + BRAND_BODY + \'</svg>\';',
  '}', '',
].join('\n');
const vectorFile = 'src/intro/brand.generated.ts';
const textureFile = 'src/intro/brandTexture.generated.ts';
const backgroundFile = 'src/intro/brandBackground.generated.ts';
const paddedSvg = '<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1120" viewBox="-80 -80 800 560">' + body + '</svg>';
const toolsModules = process.env.TIH_BRAND_TOOLS_NODE_MODULES || process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES;
const loadSharp = () => require(toolsModules ? path.join(toolsModules, 'sharp') : 'sharp');
const encode = (prefix, bytes) => "export const " + prefix + "_SHA256 = '" + sha(bytes) + "';\nexport const " + prefix + "_URI = 'data:image/png;base64," + bytes.toString('base64') + "';\n";
function backgroundModule(bytes) {
  return [
    '/** Generated from the independently authored steel-background.svg; never the reference screenshot. */',
    "export const INTRO_BACKGROUND_SOURCE_SHA256 = '" + backgroundSourceHash + "';",
    "export const INTRO_BACKGROUND_FIT = 'cover' as const;",
    'export const INTRO_BACKGROUND_WIDTH = 900;',
    'export const INTRO_BACKGROUND_HEIGHT = 1950;',
    "export const INTRO_BACKGROUND_COLOR = '#7E8BA1';",
    "export const INTRO_BACKGROUND_PALETTE = { edge: '#718097', center: '#B4BECF', ink: '#F3F3F2', base: '#7E8BA1', glint: '#FFF8EC' } as const;",
    'export const FIRST_FRAME_LOGO_WIDTH_FRACTION = 1.05;',
    'export const FIRST_FRAME_LOGO_WIDTH_CAP = 560;',
    'export const FIRST_FRAME_LOGO_CENTER_X = 0.5;',
    'export const FIRST_FRAME_LOGO_CENTER_Y = 0.46;',
    encode('INTRO_BACKGROUND', bytes),
  ].join('\n');
}
function decodeModule(file, prefix) {
  const text = read(file);
  const encoded = text.match(/data:image\/png;base64,([A-Za-z0-9+/=]+)/)?.[1];
  const expected = text.match(new RegExp(prefix + "_SHA256 = '([a-f0-9]{64})'"))?.[1];
  if (!encoded || !expected) throw new Error('Missing generated PNG data: ' + file);
  const bytes = Buffer.from(encoded, 'base64');
  if (sha(bytes) !== expected) throw new Error('Generated PNG integrity failed: ' + file);
  return bytes;
}
function verifyCopies(raster, background) {
  const image = PNG.sync.read(raster), atmosphere = PNG.sync.read(background);
  if (image.width !== 1600 || image.height !== 1120 || atmosphere.width !== 900 || atmosphere.height !== 1950) throw new Error('Shared brand raster bounds changed');
  for (const [file, bytes] of [['assets/launch/official-launch-mark.png', raster], ['assets/launch/steel-background.png', background]]) {
    if (!fs.readFileSync(path.join(root, file)).equals(bytes)) throw new Error('Native RGB copy differs from the shared PNG: ' + file);
  }
  for (const [asset, bytes] of [['LaunchLogo.imageset/official-launch-mark.png', raster], ['LaunchSteelBackground.imageset/steel-background.png', background]]) {
    const ios = path.join(root, 'ios/TuneIntoHer/Images.xcassets', asset);
    if (fs.existsSync(ios) && !fs.readFileSync(ios).equals(bytes)) throw new Error('Native iOS launch copy is stale: ' + asset);
  }
}
async function main() {
  if (process.argv.includes('--check')) {
    if (read(vectorFile) !== vector) throw new Error('Brand vector is stale');
    if (!read(textureFile).includes('Source SVG SHA-256: ' + sourceHash)) throw new Error('Brand texture source is stale');
    const raster = decodeModule(textureFile, 'BRAND_TEXTURE');
    const background = decodeModule(backgroundFile, 'INTRO_BACKGROUND');
    if (read(backgroundFile) !== backgroundModule(background)) throw new Error('Background SVG metadata or shared presentation constants are stale');
    verifyCopies(raster, background);
    if (process.argv.includes('--raster-check')) {
      const sharp = loadSharp();
      if (!(await sharp(Buffer.from(paddedSvg)).png().toBuffer()).equals(raster) || !(await sharp(Buffer.from(backgroundSource)).png().toBuffer()).equals(background)) throw new Error('SVG-to-PNG reproducibility failed');
    }
    console.log('Shared brand source, generated vector, RGBA texture and background integrity match.');
    return;
  }
  const sharp = loadSharp();
  const raster = await sharp(Buffer.from(paddedSvg)).png().toBuffer();
  const background = await sharp(Buffer.from(backgroundSource)).png().toBuffer();
  fs.writeFileSync(path.join(root, vectorFile), vector);
  fs.writeFileSync(path.join(root, textureFile), [
    '/** Generated V5 metallic RGBA foreground. Exact approved glyph geometry and kerning.',
    ' * Source SVG SHA-256: ' + sourceHash,
    ' * Original design: 640x400. Transparent padded viewBox: -80 -80 800 560, 2x raster.',
    ' * Full RGB appearance is shared verbatim; never replace it with a flat tint.',
    ' */',
    'export const PADDED_LOGO_WIDTH_SCALE = 800 / 640;',
    'export const PADDED_LOGO_HEIGHT_SCALE = 560 / 640;',
    encode('BRAND_TEXTURE', raster),
  ].join('\n'));
  fs.writeFileSync(path.join(root, backgroundFile), backgroundModule(background));
  require('../assets/launch/generate.cjs');
  console.log('Generated shared V5 metallic foreground, independent background and native RGB assets.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });

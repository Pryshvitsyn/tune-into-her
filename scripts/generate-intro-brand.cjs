/* global __dirname */
// One reviewed SVG supplies native splash, loading fallback, WebGL and Home replay.
const { Buffer } = require('node:buffer');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const sha = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const source = read('assets/brand/official-mark.svg');
const sourceHash = sha(source);
const body = source.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
const rings = body.match(/<path id="rings" d="([^"]+)"/)?.[1];
if (!rings || source.match(/viewBox="([^"]+)"/)?.[1] !== '0 0 640 400') throw new Error('Unexpected authoritative brand geometry');
if (sha(fs.readFileSync(path.join(root, 'assets/fonts/LinuxLibertineO-Regular.otf'))) !== '6332761e4fc08e30bce6f47e4a08e7d5332abe000ab6ca06c8e86bd88f456114') throw new Error('Approved typeface changed');
const vector = [
  '/** Generated by scripts/generate-intro-brand.cjs from assets/brand/official-mark.svg.',
  ' * Wordmark: exact Linux Libertine O Regular outlines, uniform scale, no added stroke.',
  ' * Two coherent open arcs; glyph-shaped clearance places lettering above the rings.',
  ' */',
  "export const BRAND_SOURCE_SHA256 = '" + sourceHash + "';",
  "export const BRAND_VIEWBOX = '0 0 640 400';",
  'export const BRAND_RATIO = 640 / 400;',
  'export const OFFICIAL_APP_MARK_PATH = ' + JSON.stringify(rings) + ';',
  'export const BRAND_BODY = ' + JSON.stringify(body) + ';',
  "export function brandSvg(ink = '#294458'): string {",
  "  if (!/^#[0-9a-fA-F]{6}$/.test(ink)) throw new Error('Invalid brand ink');",
  '  return \'<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="800" viewBox="\' + BRAND_VIEWBOX + \'" color="\' + ink + \'">\' + BRAND_BODY + \'</svg>\';',
  '}',
  '',
].join('\n');
const vectorFile = 'src/intro/brand.generated.ts';
const textureFile = 'src/intro/brandTexture.generated.ts';
const paddedSvg = '<svg xmlns="http://www.w3.org/2000/svg" width="1600" height="1120" viewBox="-80 -80 800 560" color="white">' + body + '</svg>';
const toolsModules = process.env.TIH_BRAND_TOOLS_NODE_MODULES || process.env.CODEX_PRIMARY_RUNTIME_NODE_MODULES;
const loadSharp = () => require(toolsModules ? path.join(toolsModules, 'sharp') : 'sharp');

async function main() {
  if (process.argv.includes('--check')) {
    if (read(vectorFile) !== vector) throw new Error('Brand vector is stale');
    const texture = read(textureFile);
    if (!texture.includes('Source SVG SHA-256: ' + sourceHash)) throw new Error('Brand texture source is stale');
    const encoded = texture.match(/data:image\/png;base64,([A-Za-z0-9+/=]+)/)?.[1];
    const expected = texture.match(/BRAND_TEXTURE_SHA256 = '([a-f0-9]+)'/)?.[1];
    if (!encoded || sha(Buffer.from(encoded, 'base64')) !== expected) throw new Error('Brand texture integrity failed');
    const { PNG } = require('pngjs');
    const raster = Buffer.from(encoded, 'base64');
    const image = PNG.sync.read(raster);
    const nativeBytes = fs.readFileSync(path.join(root, 'assets/launch/official-launch-mark.png'));
    const native = PNG.sync.read(nativeBytes);
    if (image.width !== 1600 || image.height !== 1120 || native.width !== image.width || native.height !== image.height) throw new Error('Brand texture bounds changed');
    for (let i = 0; i < image.data.length; i += 4) {
      if (native.data[i + 3] !== image.data[i + 3] || native.data[i] !== 0x29 || native.data[i + 1] !== 0x44 || native.data[i + 2] !== 0x58) throw new Error('Native launch pixels differ from the shared texture');
    }
    const ios = path.join(root, 'ios/TuneIntoHer/Images.xcassets/LaunchLogo.imageset/official-launch-mark.png');
    if (fs.existsSync(ios) && !nativeBytes.equals(fs.readFileSync(ios))) throw new Error('Native iOS launch copy is stale');
    if (process.argv.includes('--raster-check')) {
      const regenerated = await loadSharp()(Buffer.from(paddedSvg)).png().toBuffer();
      if (!regenerated.equals(raster)) throw new Error('SVG-to-texture reproducibility failed');
    }
    console.log('Shared brand source, generated vector and texture integrity match.');
    return;
  }
  // Same optional sharp runtime used by existing repository asset generators.
  const raster = await loadSharp()(Buffer.from(paddedSvg)).png().toBuffer();
  fs.writeFileSync(path.join(root, vectorFile), vector);
  fs.writeFileSync(path.join(root, textureFile), [
    '/** Generated by scripts/generate-intro-brand.cjs. Exact approved font outlines.',
    ' * Source SVG SHA-256: ' + sourceHash,
    ' * Original design: 640x400. Transparent padded viewBox: -80 -80 800 560, 2x raster.',
    ' */',
    'export const PADDED_LOGO_WIDTH_SCALE = 800 / 640;',
    'export const PADDED_LOGO_HEIGHT_SCALE = 560 / 640;',
    "export const BRAND_TEXTURE_SHA256 = '" + sha(raster) + "';",
    "export const BRAND_TEXTURE_URI = 'data:image/png;base64," + raster.toString('base64') + "';",
    '',
  ].join('\n'));
  require('../assets/launch/generate.cjs');
  console.log('Generated shared brand vector, texture and native launch assets.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
